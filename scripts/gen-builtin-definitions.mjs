// Generate apps/web-ui/src/lib/builtin-definitions.ts from the builtin YAMLs.
//
// web-ui cannot read them itself: it is outside the npm workspace and parsing YAML
// would need a dependency it does not carry. So the graphs were transcribed BY HAND,
// and hand copies rot — `feature-planning` sat at 2 nodes while the YAML grew to 9,
// so the run-detail page drew a graph that had not existed for months.
//
// Generating it keeps the copy but removes the transcription: the source of truth is
// the YAML, and scripts/check-builtin-definitions-drift.sh fails the moment the two
// disagree. Same shape as gen:catalog / check-catalog-drift.sh.
//
// Only the fields the web UI actually renders are emitted — `type` drives the node
// icon and `signal` labels a wait node ("Waiting for the spec PR"). Prose fields are
// left out: they would bloat the file and nothing reads them.

import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { loadBuiltinAssemblyLines } from "@re-cinq/lore-assembly-lines";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const LIB_DIR = resolve(ROOT, "apps/web-ui/src/lib");
const DEST = resolve(LIB_DIR, "builtin-definitions.ts");
const PR_REVIEW_DEST = resolve(LIB_DIR, "builtin-definitions-pr-review.ts");
const INTERNAL_EVENT_DEST = resolve(
  LIB_DIR,
  "builtin-definitions-internal-events.ts",
);

// The PR-review family (specs/code-review-assembly-line) and the internal-event
// family (specs/detection-assembly-lines + the ingest line: started by a
// cron/internal event, run one deterministic station, and finish — no PR) each
// already read as one idea, so they get their own generated sibling file to
// keep the main one under `max-lines` — splitting a growing generated file by
// hand-picked line count would rot the same way the original hand-transcription
// did.
const PR_REVIEW_NAMES = new Set([
  "code-review",
  "code-review-recheck",
  "code-review-reply",
  "comment-triage",
]);
const INTERNAL_EVENT_NAMES = new Set([
  "gap-detect",
  "ingest",
  "spec-coverage-backfill",
  "spec-coverage-validate",
  "spec-drift",
]);

/** `feature-planning` -> `featurePlanningDefinition`. */
function constName(name) {
  const camel = name.replace(/-([a-z])/g, (_, c) => c.toUpperCase());

  return `${camel}Definition`;
}

function emitNode(node) {
  const parts = [
    `id: ${JSON.stringify(node.id)}`,
    `type: ${JSON.stringify(node.type)}`,
  ];

  if (node.validator) {
    parts.push(`validator: ${JSON.stringify(node.validator)}`);
  }

  if (node.signal) {
    parts.push(`signal: ${JSON.stringify(node.signal)}`);
  }

  return `    { ${parts.join(", ")} },`;
}

function emitEdge(edge) {
  const parts = [
    `from: ${JSON.stringify(edge.from)}`,
    `to: ${JSON.stringify(edge.to)}`,
    `on: ${JSON.stringify(edge.on)}`,
  ];

  if (edge.iteration_max !== undefined) {
    parts.push(`iteration_max: ${edge.iteration_max}`);
  }

  return `    { ${parts.join(", ")} },`;
}

function emitDefinition(line) {
  return [
    `export const ${constName(line.name)}: AssemblyLineDefinition = {`,
    `  name: ${JSON.stringify(line.name)},`,
    `  description: ${JSON.stringify(line.description.trim())},`,
    `  version: 1,`,
    `  entry: ${JSON.stringify(line.entry)},`,
    `  exit: ${JSON.stringify(line.exit)},`,
    `  nodes: [`,
    ...line.nodes.map(emitNode),
    `  ],`,
    `  edges: [`,
    ...line.edges.map(emitEdge),
    `  ],`,
    `};`,
  ].join("\n");
}

const allLines = [...(await loadBuiltinAssemblyLines()).values()].sort(
  (a, b) => a.name.localeCompare(b.name),
);
const prReviewLines = allLines.filter((l) => PR_REVIEW_NAMES.has(l.name));
const internalEventLines = allLines.filter((l) =>
  INTERNAL_EVENT_NAMES.has(l.name),
);
const mainLines = allLines.filter(
  (l) => !PR_REVIEW_NAMES.has(l.name) && !INTERNAL_EVENT_NAMES.has(l.name),
);

function genHeader(note) {
  return `// GENERATED by scripts/gen-builtin-definitions.mjs — do not edit; regenerate with \`npm run gen:builtin-definitions\`. web-ui is outside the npm workspace and carries no YAML parser, so it needs this copy; generating it is what stops it rotting (it once claimed feature-planning had 2 nodes while the YAML had 9).${note}`;
}

function siblingFile(header, lines) {
  return [
    header,
    "",
    'import type { AssemblyLineDefinition } from "./assembly-line-definition";',
    "",
    ...lines.map((l) => `${emitDefinition(l)}\n`),
  ].join("\n");
}

const prReviewFile = siblingFile(
  genHeader(" The PR-review family."),
  prReviewLines,
);
const internalEventFile = siblingFile(
  genHeader(" The internal-event family."),
  internalEventLines,
);

const mainFile = [
  genHeader(""),
  "",
  'import type { AssemblyLineDefinition } from "./assembly-line-definition";',
  "import {",
  ...prReviewLines.map((l) => `  ${constName(l.name)},`),
  '} from "./builtin-definitions-pr-review";',
  "import {",
  ...internalEventLines.map((l) => `  ${constName(l.name)},`),
  '} from "./builtin-definitions-internal-events";',
  "",
  'export * from "./builtin-definitions-pr-review";',
  'export * from "./builtin-definitions-internal-events";',
  "",
  ...mainLines.map((l) => `${emitDefinition(l)}\n`),
  "export const builtinDefinitions: AssemblyLineDefinition[] = [",
  ...prReviewLines.map((l) => `  ${constName(l.name)},`),
  ...internalEventLines.map((l) => `  ${constName(l.name)},`),
  ...mainLines.map((l) => `  ${constName(l.name)},`),
  "];",
  "",
].join("\n");

writeFileSync(PR_REVIEW_DEST, prReviewFile);
writeFileSync(INTERNAL_EVENT_DEST, internalEventFile);
writeFileSync(DEST, mainFile);
// Prettier owns the final shape. Without this the repo's format job reflows the
// generated file and the drift check then compares against something the generator
// never produces — it would fail on every run, for no real drift.
// --no-install: if prettier is not already in node_modules, fail loudly rather
// than silently fetching a different version and producing output the drift
// check can never match.
execFileSync(
  "npx",
  [
    "--no-install",
    "prettier",
    "--write",
    PR_REVIEW_DEST,
    INTERNAL_EVENT_DEST,
    DEST,
  ],
  { cwd: ROOT, stdio: "ignore" },
);
console.log(
  `[gen-builtin-definitions] wrote ${DEST}, ${PR_REVIEW_DEST}, ${INTERNAL_EVENT_DEST} (${allLines.length} definitions)`,
);
